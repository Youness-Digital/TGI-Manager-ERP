const MODEL_ALIASES = Object.freeze({
  commandes: "bons",
});

function resolveModel(collectionName) {
  const modelName = MODEL_ALIASES[collectionName] || collectionName;
  return ERP_MODELS[modelName] || null;
}

export function getModelDefinition(collectionName) {
  return resolveModel(collectionName);
}

export function createModelRecord(collectionName, record = {}) {
  const model = resolveModel(collectionName);
  if (!model) return { ...record };

  const defaults = model.defaults();
  const result = { ...defaults, ...record };
  if (result.status == null || result.status === "") {
    result.status = model.defaultStatus;
  }
  return result;
}

export function normalizeModelRecord(collectionName, record = {}) {
  return createModelRecord(collectionName, record);
}
